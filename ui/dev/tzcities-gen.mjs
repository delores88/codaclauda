/* Generates ui/app/city/tzcities.js from a local copy of IANA tzdb zone1970.tab (public domain):
 * each zone's principal location (ISO 6709) rounded to 0.1° plus a city label from the zone name.
 * Offline: it reads the file you give it and never downloads anything.
 *   node ui/dev/tzcities-gen.mjs <zone1970.tab> <out.js> [--source URL] [--last-modified HTTP-date] [--date YYYY-MM-DD] */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const round1 = n => { const r = Math.round(n * 10) / 10; return r === 0 ? 0 : r; };
/** ±DDMM±DDDMM or ±DDMMSS±DDDMMSS → [lat, lon] in degrees, or null. */
export function parseIso6709(text) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(String(text || '').trim());
  if (!m) return null;
  const deg = (sign, d, mm, ss = '0') => (sign === '-' ? -1 : 1) * (Number(d) + Number(mm) / 60 + Number(ss) / 3600);
  const lat = deg(m[1], m[2], m[3], m[4]), lon = deg(m[5], m[6], m[7], m[8]);
  return Math.abs(lat) <= 90 && Math.abs(lon) <= 180 ? [lat, lon] : null;
}
/** 'America/Argentina/Buenos_Aires' → 'Buenos Aires'. */
export const zoneLabel = zone => String(zone || '').split('/').pop().replaceAll('_', ' ');
/** zone1970.tab text → { rows: [{ zone, lat, lon, label }], version } (version only if the header states one). */
export function parseZoneTab(text) {
  const rows = [], seen = new Set();
  let version = '';
  for (const line of String(text).split(/\r?\n/)) {
    if (line.startsWith('#')) { version ||= /\bversion\s+(\d{4}[a-z])\b/i.exec(line)?.[1] || ''; continue; }
    if (!line.trim()) continue;
    const [, coords, zone] = line.split('\t');
    const at = parseIso6709(coords);
    if (!at || !/^[A-Za-z][A-Za-z0-9_+\-/]*$/.test(zone || '') || seen.has(zone)) continue;
    seen.add(zone);
    rows.push({ zone, lat: round1(at[0]), lon: round1(at[1]), label: zoneLabel(zone) });
  }
  return { rows, version };
}
export function renderModule({ rows, version }, { source, lastModified = '', date }) {
  const head = [
    '/* Generated by ui/dev/tzcities-gen.mjs. Do not edit by hand.',
    ` * Source: ${source}`,
    lastModified ? ` *   (IANA tzdb zone1970.tab; HTTP Last-Modified: ${lastModified})` : ' *   (IANA tzdb zone1970.tab)',
    ` * tzdb version: ${version || 'not stated in the file header'}.`,
    ' * zone1970.tab is in the public domain; this derived table is too.',
    ` * Generated ${date}. ${rows.length} zones.`,
    ' * zone → [latitude, longitude, city label]: the zone\'s principal location rounded to 0.1°',
    ' * (about 10 km) and the label from its name. Used only as an approximate default location. */',
    'export const TZ_CITIES = {',
  ];
  const body = rows.map(r => `${JSON.stringify(r.zone)}:[${r.lat},${r.lon},${JSON.stringify(r.label)}],`);
  return `${head.join('\n')}\n${body.join('\n')}\n};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [input, output, ...rest] = process.argv.slice(2);
  if (!input || !output) { console.error('usage: node ui/dev/tzcities-gen.mjs <zone1970.tab> <out.js> [--source URL] [--last-modified DATE] [--date YYYY-MM-DD]'); process.exit(2); }
  const opt = name => { const k = rest.indexOf(name); return k >= 0 ? rest[k + 1] : undefined; };
  const parsed = parseZoneTab(readFileSync(input, 'utf8'));
  if (parsed.rows.length < 200) { console.error(`Only ${parsed.rows.length} zones parsed; refusing to write.`); process.exit(1); }
  writeFileSync(output, renderModule(parsed, {
    source: opt('--source') || 'https://data.iana.org/time-zones/tzdb/zone1970.tab',
    lastModified: opt('--last-modified') || '',
    date: opt('--date') || new Date().toISOString().slice(0, 10),
  }));
  console.log(`Wrote ${parsed.rows.length} zones to ${output}`);
}
